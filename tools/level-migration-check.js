// Exercise the real store load/import paths without a browser.
const assert = require('node:assert/strict'), fs = require('node:fs'), load = require('./load-page');
const engine = load('src/engine.js');
const transferSource = fs.readFileSync('src/transfer.js','utf8').replace(/^export /gm,'');
const transfer = new Function(transferSource + ';return {encodeTransfer,decodeTransfer};')();
const source = fs.readFileSync('src/store.js','utf8');
const imports = [...source.matchAll(/^import \{ (.+) \} from .+;$/gm)].flatMap(m => m[1].split(',').map(x => x.trim()));
const data = new Map();
const fixture = engine.blankSession();
fixture.players = [2.375, 5, 5.8].map((skill,i)=>({id:'p'+i,name:'Player '+i,skill,pref:'any',paused:false,readyAt:Date.now()}));
fixture.queueMatching='equalSkill';
data.set(engine.LS_KEY, JSON.stringify({currentId:fixture.id,sessions:[fixture]}));
const storage = {getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v)};
const dependencies = { ...transfer, useSyncExternalStore(){} };
for(const name of imports) if(!(name in dependencies)) dependencies[name]=engine.get(name);
const mocks = {localStorage:storage,addEventListener(){},setInterval(){},matchMedia:()=>({matches:false,addEventListener(){}}),document:{documentElement:{classList:{toggle(){}}}}};
const keys=[...imports,...Object.keys(mocks)];
const store = new Function(...keys,source.replace(/^import .+;$/gm,'').replace(/^export /gm,'')+';return {importData};')(...imports.map(k=>dependencies[k]),...Object.values(mocks));
assert.deepEqual(engine.get("getS")().players.map(p=>p.skill),[2.6,5,5.8]);
assert.equal(engine.matchingMode(),'auto');
assert.equal(engine.level(engine.get("getS")().players[1].skill),6,'old top position becomes High adv');
assert.equal(engine.level(engine.get("getS")().players[2].skill),7,'new Pro survives a reload');
const incoming={...fixture,id:'imported',players:fixture.players.map(p=>({...p,levelSet:123,levelSnooze:456}))};
store.importData(transfer.encodeTransfer([incoming],incoming.id));
assert.deepEqual(engine.get("getS")().players.map(p=>p.skill),[2.6,5,5.8]);
assert.equal(engine.matchingMode(),'auto');
assert(engine.get("getS")().players.every(p=>p.levelSet===123&&p.levelSnooze===456),'review evidence dates survive import');
assert.equal(JSON.parse(data.get(engine.LS_KEY)).sessions.length,2,'existing sessions retained');
console.log('Seven-level load/import migration checks pass.');
